function flag(code) {
  return code.toUpperCase().replace(/./g, (char) => String.fromCodePoint(127397 + char.charCodeAt(0)));
}

function buildPlaces() {
  const countries = COUNTRIES.map(([code, name, dial, example, digits], index) => ({
    id: index + 1,
    code,
    name,
    dial,
    flag: flag(code),
    example,
    digits,
    active: 1,
    sort_order: code === "PK" ? 0 : index + 1,
  }));
  const cities = [];
  let id = 1;
  for (const [code, names] of Object.entries(CITIES)) {
    names.forEach((name, index) => {
      cities.push({ id, country_code: code, name, active: 1, sort_order: index + 1 });
      id += 1;
    });
  }
  return { countries, cities };
}

module.exports = { buildPlaces };
